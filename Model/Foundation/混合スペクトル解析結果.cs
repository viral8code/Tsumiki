namespace Tsumiki.Model.Foundation
{
    /// <summary>
    /// k-mer 出現回数ヒストグラムを「誤り成分 (裾の重い幾何分布) ＋ 真の k-mer 成分
    /// (単一コピー平均 λ の整数倍に山を持つ、コピー数上限までのポアソン混合)」の
    /// 2 成分混合モデルとして EM 推定した結果
    /// </summary>
    /// <remarks>
    /// A_カットオフ と A_信頼下限 は、同じ事後誤り確率の曲線を異なる有意水準側から
    /// 見た 2 つの境界<br/>
    /// 前者は「これ以上は使ってよい」、後者は「これ以上は誤り成分が
    /// 全く混じらないので判定を待たず無条件に信頼してよい」を意味する
    /// </remarks>
    internal record 混合スペクトル解析結果(double A_単一コピー平均, ulong A_カットオフ, ulong A_信頼下限, double A_誤り成分の混合比, double A_誤り成分の平均, int A_反復回数);
}
