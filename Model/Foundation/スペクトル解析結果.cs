namespace Tsumiki.Model
{
    /// <summary>
    /// k-mer 出現回数ヒストグラム(k-mer スペクトル)の解析結果。
    ///
    /// 実データのスペクトルは二峰性になる。出現回数1付近にシーケンスエラー由来の
    /// 巨大な山があり、そこから離れたところに真のゲノム由来の山がある。
    /// 前者と後者を分ける「谷」がカットオフの適正値であり、後者の山の位置が
    /// 1コピーあたりの k-mer カバレッジになる。
    /// </summary>
    internal record スペクトル解析結果(
        ulong A_谷,
        ulong A_ピーク出現回数,
        long A_谷の頻度,
        long A_ピークの頻度,
        long A_ゲノム由来の延べ数,
        long A_延べ数の総和,
        long A_推定ゲノムサイズ);
}
