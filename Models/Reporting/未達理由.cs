namespace Tsumiki.Models.Reporting
{
    /// <summary>
    /// 完全長に届かなかった理由
    /// </summary>
    internal enum 未達理由
    {
        /// <summary>
        /// グラフから期待される k-mer の取りこぼしが許容範囲を超えている
        /// </summary>
        取りこぼしが多い,

        /// <summary>
        /// グラフに含まれるべきでない k-mer の出現が許容範囲を超えている
        /// </summary>
        出しすぎている,

        /// <summary>
        /// グラフ整合の自己検査自体を実行できなかった
        /// </summary>
        自己検査を行えなかった,

        /// <summary>
        /// scaffold のギャップが埋まらずに残っている
        /// </summary>
        未解決のギャップが残る,

        /// <summary>
        /// 伸長中に一意へ絞り込めなかった分岐が残っている
        /// </summary>
        決めきれない分岐が残る,

        /// <summary>
        /// リードの再マッピング深度が接合点の前後で途切れている
        /// </summary>
        深度が不連続,

        /// <summary>
        /// 深度の連続性チェック自体を行っていない
        /// </summary>
        深度を測っていない,

        /// <summary>
        /// 配列が環状ゲノムとして閉じていない
        /// </summary>
        環状に閉じていない,

        /// <summary>
        /// 環状の閉じ目がリードで裏付けられていない
        /// </summary>
        閉じ目がリードで裏付けられない,

        /// <summary>
        /// 環状閉鎖の検証自体を行っていない
        /// </summary>
        環状閉鎖を検証していない,

        /// <summary>
        /// 元リードで裏付けられない箇所が配列中に残っている
        /// </summary>
        リードに裏付けの無い箇所がある,

        /// <summary>
        /// リードによる支持の有無を調べていない
        /// </summary>
        リードの支持を調べていない,
    }
}
