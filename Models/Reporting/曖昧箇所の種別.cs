namespace Tsumiki.Models.Reporting
{
    /// <summary>
    /// 決めきれずに打ち切った箇所の区分
    /// </summary>
    internal enum 曖昧箇所の種別
    {
        /// <summary>
        /// どの候補にも証拠が無く、伸ばす根拠が得られなかった
        /// </summary>
        支持なし,

        /// <summary>
        /// 首位と次点の差が小さく、一方に確定できなかった
        /// </summary>
        僅差,

        /// <summary>
        /// 両端を繋ぐ経路が複数あり、どれか 1 本に定まらなかった
        /// </summary>
        経路が一意でない,

        /// <summary>
        /// 両端を繋ぐ経路がグラフ上に見つからなかった
        /// </summary>
        到達不能,

        /// <summary>
        /// 分岐元が多コピーで、いまどのコピーの上にいるのかを区別できなかった
        /// </summary>
        反復の内側,

        /// <summary>
        /// 両端の足場そのものが信頼できる k-mer 集合に無く、探索を始められなかった
        /// </summary>
        アンカー不足,

        /// <summary>
        /// 足場に当たる局所リードが 1 本も集まらなかった
        /// </summary>
        リード無し,

        /// <summary>
        /// 探索状態数が上限に達し、経路の有無も決められないまま打ち切った
        /// </summary>
        探索打切り,
    }
}
